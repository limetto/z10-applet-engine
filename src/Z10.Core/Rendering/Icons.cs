    /// <summary>Alle eingebauten Symbolnamen.</summary>
    public static IEnumerable<string> BuiltInNames => Art.Keys;

    /// <summary>Für ältere Dateien: Namen → Hex-Darstellung (nur zur Anzeige).</summary>
    public static readonly IReadOnlyDictionary<string, string> BuiltIn =
        Art.ToDictionary(kv => kv.Key, kv => string.Join(" ", kv.Value.Select(RowHex)), StringComparer.OrdinalIgnoreCase);

    public static bool IsBuiltIn(string name) => Art.ContainsKey(name.Trim());

    /// <summary>Symbol als Einzelbild (bei Animationen das passende Bild zur Zeit <paramref name="timeMs"/>).</summary>
    public static MonoBitmap Get(string spec, ImageLibrary? images = null, long timeMs = 0)
    {
        spec = (spec ?? "").Trim();
        if (spec.StartsWith(ImagePrefix, StringComparison.OrdinalIgnoreCase))
            return images?.Get(spec[ImagePrefix.Length..])?.FrameAt(timeMs) ?? Placeholder();
        if (Art.TryGetValue(spec, out var rows)) return FromArt(rows);
        return ParseHex(spec);
    }

    /// <summary>Kompatibel zu älteren Versionen: Name oder Hex-Zeilen.</summary>
    public static MonoBitmap Parse(string spec) => Get(spec);

    public static MonoBitmap FromArt(string[] rows)
    {
        int w = rows.Max(r => r.Length);
        var bmp = new MonoBitmap(w, rows.Length);
        for (int y = 0; y < rows.Length; y++)
            for (int x = 0; x < rows[y].Length; x++)
                bmp[x, y] = rows[y][x] == '#';
        return bmp;
    }

    /// <summary>Hex-Zeilen: je Zeile 2 Hex-Ziffern pro 8 Pixel, linkes Pixel = höchstwertiges Bit.</summary>
    public static MonoBitmap ParseHex(string spec)
    {
        var parts = spec.Split(new[] { ' ', ',', ';', '\n', '\r', '\t' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(p => p.Replace("0x", "", StringComparison.OrdinalIgnoreCase)).ToArray();
        if (parts.Length == 0) return Placeholder();
        int w = Math.Clamp(parts.Max(p => p.Length) * 4, 1, 160);
        var bmp = new MonoBitmap(w, Math.Min(parts.Length, 32));
        for (int y = 0; y < bmp.Height; y++)
        {
            var row = parts[y];
            for (int i = 0; i < row.Length; i++)
            {
                int nibble = Uri.IsHexDigit(row[i]) ? Convert.ToInt32(row[i].ToString(), 16) : 0;
                for (int b = 0; b < 4; b++)
                    bmp[i * 4 + b, y] = (nibble & (0x8 >> b)) != 0;
            }
        }
        return bmp;
    }

    private static string RowHex(string row)
    {
        var sb = new System.Text.StringBuilder();
        for (int i = 0; i < row.Length; i += 4)
        {
            int n = 0;
            for (int b = 0; b < 4 && i + b < row.Length; b++) if (row[i + b] == '#') n |= 0x8 >> b;
            sb.Append(n.ToString("X"));
        }
        return sb.ToString();
    }

    private static MonoBitmap Placeholder()
    {
        var b = new MonoBitmap(8, 8);
        b.DrawRect(0, 0, 8, 8);
        b.DrawLine(0, 0, 7, 7);
        b.DrawLine(7, 0, 0, 7);
        return b;
    }
