    public bool HasGlyph(char c) => _glyphs.ContainsKey(c);

    /// <summary>Spalten eines Zeichens, bereits auf die genutzte Breite beschnitten.</summary>
    public ReadOnlySpan<byte> GetColumns(char c)
    {
        if (c == ' ') return new byte[SpaceWidth];
        if (!_glyphs.TryGetValue(c, out var g)) g = _glyphs['?'];
        if (char.IsDigit(c)) return g;               // Tabellenziffern
        int start = 0, end = g.Length;
        while (start < end && g[start] == 0) start++;
        while (end > start && g[end - 1] == 0) end--;
        return start == end ? new byte[SpaceWidth] : g.AsSpan(start, end - start);
    }

    public int Measure(string text, int scale = 1)
    {
        if (string.IsNullOrEmpty(text)) return 0;
        int w = 0;
        foreach (var c in text) w += GetColumns(c).Length + Spacing;
        return (w - Spacing) * scale;
    }

    public int LineHeight(int scale = 1) => GlyphHeight * scale;

    public MonoBitmap Render(string text, int scale = 1)
    {
        scale = Math.Clamp(scale, 1, 4);
        var bmp = new MonoBitmap(Math.Max(0, Measure(text, scale)), GlyphHeight * scale);
        int x = 0;
        foreach (var c in text)
        {
            var cols = GetColumns(c);
            for (int col = 0; col < cols.Length; col++)
                for (int row = 0; row < GlyphHeight; row++)
                    if ((cols[col] & (1 << row)) != 0)
                        bmp.FillRect(x + col * scale, row * scale, scale, scale);
            x += (cols.Length + Spacing) * scale;
        }
        return bmp;
    }
